#!/usr/bin/env python3
"""Regenerate every uv dependency lock from the command in its own header.

Dependabot only updates requirements.txt, so the locks derived from it (the
Windows runtime and test locks) drift unless they are compiled again. uv keeps
the versions already in each output file, so only changed inputs move.

CI runs this and fails on any diff; run it locally and commit the result.
"""

from __future__ import annotations

import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# This file was autogenerated by uv via the following command:"

# Inputs before the locks that include or exclude them.
LOCKS = [
    "requirements.txt",
    "requirements-test.txt",
    "packaging/windows/requirements-runtime-windows.txt",
    "packaging/windows/requirements-test-windows.txt",
    "packaging/windows/requirements-build.txt",
]


def is_uv_lock(path: Path) -> bool:
    with path.open(encoding="utf-8") as handle:
        return handle.readline().rstrip("\n") == HEADER


def lock_command(lock: str) -> list[str]:
    lines = (ROOT / lock).read_text(encoding="utf-8").splitlines()
    if len(lines) < 2 or lines[0] != HEADER:
        raise SystemExit(f"{lock}: missing the uv header")
    command = shlex.split(lines[1].lstrip("# "))
    if command[:3] != ["uv", "pip", "compile"] or command[-2:] != ["-o", lock]:
        raise SystemExit(f"{lock}: header is not a 'uv pip compile ... -o {lock}' command")
    return command


def unlisted_locks() -> list[str]:
    found = {
        path.relative_to(ROOT).as_posix()
        for pattern in ("requirements*.txt", "packaging/windows/requirements*.txt")
        for path in ROOT.glob(pattern)
        if is_uv_lock(path)
    }
    return sorted(found - set(LOCKS))


def main() -> int:
    missing = unlisted_locks()
    if missing:
        raise SystemExit(f"Add these uv locks to LOCKS in scripts/sync_locks.py: {', '.join(missing)}")
    for lock in LOCKS:
        subprocess.run([*lock_command(lock), "--quiet"], cwd=ROOT, check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
